import { describe, expect, it } from 'vitest';
import { run } from './helpers';

describe('사칙연산과 정밀도', () => {
  it.each([
    ['1+2', '3'],
    ['0.1+0.2', '0.3'], // 2진 부동소수점이면 0.30000000000000004
    ['1/3*3', '1'], // 유리수로 유지되므로 정확히 1
    ['2/3', '0.6666666667'], // 10자리 반올림 (half-up)
    ['1/7', '0.1428571429'],
    ['10-0.1', '9.9'],
    ['0.1*3', '0.3'],
    ['1/81', '0.01234567901'],
    ['123456789*9', '1111111101'],
    ['99999*99999', '9999800001'],
  ])('%s = %s', (expr, want) => expect(run(expr)).toBe(want));
});

describe('우선순위', () => {
  it.each([
    ['2+3*4', '14'],
    ['(2+3)*4', '20'],
    ['10-4-3', '3'], // 좌결합
    ['64/4/2', '8'],
    ['6/2(1+2)', '1'], // ES PLUS: 생략된 곱셈이 ÷보다 먼저
    ['6/2*(1+2)', '9'], // 명시적 ×는 ÷와 같은 순위
    ['2(3)(4)', '24'],
    ['(1+1)(2+2)', '8'],
    ['~2²', '-4'], // (-)는 x²보다 약하다
    ['(~2)²', '4'],
    ['-2²', '-4'], // 식 맨 앞의 − 도 부호
    ['2²²', '16'],
    ['4⁻', '0.25'],
    ['2⁻*8', '4'],
  ])('%s = %s', (expr, want) => expect(run(expr)).toBe(want));
});

describe('부호', () => {
  it.each([
    ['~3-~2', '-1'],
    ['2*~3', '-6'],
    ['2*-3', '-6'],
    ['~~5', '5'],
    ['5--2', '7'],
    ['~(2+3)', '-5'],
  ])('%s = %s', (expr, want) => expect(run(expr)).toBe(want));
});

describe('괄호 자동 닫힘', () => {
  it.each([
    ['2(3+4', '14'],
    ['((1+2', '3'],
    ['(2', '2'],
  ])('%s = %s', (expr, want) => expect(run(expr)).toBe(want));
});

describe('지수 표기 (×10^x)', () => {
  it.each([
    ['2E3', '2000'],
    ['E3', '1000'],
    ['2E~2', '0.02'],
    ['2E~3', '2e-3'], // Norm1: 0.01 미만은 지수 표기
    ['1.5E2+1', '151'],
  ])('%s = %s', (expr, want) => expect(run(expr)).toBe(want));
});

describe('Norm1 표시 경계', () => {
  it.each([
    ['9999999999', '9999999999'],
    ['9999999999+1', '1e10'],
    ['12345678901', '1.23456789e10'], // 10자리 반올림: 1.234567890 → 끝 0 제거
    ['0.01', '0.01'],
    ['0.009', '9e-3'],
    ['1/300', '3.333333333e-3'],
    ['99999999995', '1e11'], // 9.9999999995 → 반올림 자리올림
  ])('%s → %s', (expr, want) => expect(run(expr)).toBe(want));
});

describe('오류', () => {
  it.each([
    ['1/0', 'Math ERROR'],
    ['2++', 'Syntax ERROR'],
    ['2+3)', 'Syntax ERROR'],
    ['*2', 'Syntax ERROR'],
    ['1..2', 'Syntax ERROR'],
    ['()', 'Syntax ERROR'],
    ['2E', 'Syntax ERROR'],
    ['0⁻', 'Math ERROR'],
    ['E99*10', 'Math ERROR'], // 10^100 이상은 범위 초과
    ['A2', 'Syntax ERROR'], // 숫자 앞에서는 곱셈 기호를 생략할 수 없다
  ])('%s → %s', (expr, want) => expect(run(expr)).toBe(want));
});
